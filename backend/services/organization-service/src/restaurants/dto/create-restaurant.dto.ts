import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import {
  ArrayUnique,
  IsArray,
  IsBoolean,
  IsEmail,
  IsNotEmpty,
  IsOptional,
  IsString,
  IsUUID,
  Matches,
  MaxLength,
} from 'class-validator';
import { CodeCase, DisplayName } from '../../common/display-name.decorator';
import { GSTIN_PATTERN } from '../../legal-entities/legal-entity-guards';

const timePattern = /^([01]\d|2[0-3]):[0-5]\d$/;
// Indian formats, checked once a code is trimmed and in capitals (@CodeCase runs first).
const panPattern = /^[A-Z]{5}\d{4}[A-Z]$/;
const ifscPattern = /^[A-Z]{4}0[A-Z0-9]{6}$/;

export class CreateRestaurantDto {
  @ApiProperty()
  @IsUUID()
  hospitalId!: string;

  @ApiPropertyOptional()
  @IsOptional()
  @IsUUID()
  locationId?: string;

  @ApiPropertyOptional()
  @IsOptional()
  @IsUUID()
  storeId?: string;

  @ApiPropertyOptional()
  @IsOptional()
  @IsUUID()
  kitchenId?: string;

  @ApiPropertyOptional({ description: 'Kitchens mapped to this restaurant.', type: [String] })
  @IsArray()
  @ArrayUnique()
  @IsOptional()
  @IsUUID('4', { each: true })
  kitchenIds?: string[];

  @ApiProperty({ example: 'Main Cafeteria' })
  @IsNotEmpty()
  @IsString()
  @MaxLength(255)
  @DisplayName()
  restaurantName!: string;

  @ApiPropertyOptional({
    description: 'Generated by the service for new restaurants. Existing values remain supported.',
    example: 'RST0001',
  })
  // Optional, but an update may not blank it.
  @IsNotEmpty()
  @IsOptional()
  @IsString()
  @MaxLength(50)
  @CodeCase()
  restaurantCode?: string;

  @ApiPropertyOptional({ example: 'cafeteria@max.local' })
  @IsEmail()
  @IsOptional()
  @MaxLength(255)
  email?: string;

  @ApiPropertyOptional({ example: '9999999999' })
  @IsOptional()
  @IsString()
  @Matches(/^\d{10}$/, { message: 'mobile must be a 10 digit number.' })
  @MaxLength(30)
  mobile?: string;

  @ApiPropertyOptional({ example: 'https://example.com/thumbnail.jpg' })
  @IsOptional()
  @IsString()
  @MaxLength(500)
  thumbnailUrl?: string;

  @ApiPropertyOptional({ example: 'https://example.com/cover.jpg' })
  @IsOptional()
  @IsString()
  @MaxLength(500)
  coverImageUrl?: string;

  @ApiPropertyOptional({ example: '07AADCM0815B1ZQ' })
  @IsOptional()
  @IsString()
  @Matches(GSTIN_PATTERN, { message: 'gstNumber must be a valid 15-character GSTIN.' })
  @MaxLength(50)
  @CodeCase()
  gstNumber?: string;

  @ApiPropertyOptional({ example: 'ABCDE1234F' })
  @IsOptional()
  @IsString()
  @Matches(panPattern, { message: 'panNumber must be a valid 10-character PAN.' })
  @MaxLength(50)
  @CodeCase()
  panNumber?: string;

  @ApiPropertyOptional({ example: 'FSSAI123456' })
  @IsOptional()
  @IsString()
  @MaxLength(500)
  fssaiNumber?: string;

  @ApiPropertyOptional({ example: '12345678901234, 98765432109876' })
  @IsOptional()
  @IsString()
  @MaxLength(500)
  fssaiNumbers?: string;

  @ApiPropertyOptional({ example: 'Max Healthcare Cafeteria Unit' })
  @IsOptional()
  @IsString()
  @MaxLength(255)
  @DisplayName()
  legalName?: string;

  @ApiPropertyOptional({ example: 'Ground Floor, Main Building' })
  @IsOptional()
  @IsString()
  @MaxLength(500)
  gstAddress?: string;

  @ApiPropertyOptional({ default: false })
  @IsBoolean()
  @IsOptional()
  isRegisteredInGst?: boolean;

  @ApiPropertyOptional({ example: 'Ground Floor' })
  @IsOptional()
  @IsString()
  @MaxLength(500)
  address?: string;

  @ApiPropertyOptional({ example: '07:00' })
  @IsOptional()
  @Matches(timePattern, { message: 'openingTime must use HH:mm format.' })
  openingTime?: string;

  @ApiPropertyOptional({ example: '23:00' })
  @IsOptional()
  @Matches(timePattern, { message: 'closingTime must use HH:mm format.' })
  closingTime?: string;

  @ApiPropertyOptional({ default: false })
  @IsBoolean()
  @IsOptional()
  normalDiscountApplicable?: boolean;

  @ApiPropertyOptional({ default: false })
  @IsBoolean()
  @IsOptional()
  staffDiscountApplicable?: boolean;

  @ApiPropertyOptional({ default: false })
  @IsBoolean()
  @IsOptional()
  onlineOrderingEnabled?: boolean;

  @ApiPropertyOptional({ default: false })
  @IsBoolean()
  @IsOptional()
  inRoomDiningEnabled?: boolean;

  @ApiPropertyOptional({ default: false })
  @IsBoolean()
  @IsOptional()
  b2cQrEnabled?: boolean;

  @ApiPropertyOptional({ default: false })
  @IsBoolean()
  @IsOptional()
  offline?: boolean;

  @ApiPropertyOptional({ default: false })
  @IsBoolean()
  @IsOptional()
  isOffline?: boolean;

  @ApiPropertyOptional({ default: false, description: 'IHC only' })
  @IsBoolean()
  @IsOptional()
  isIhcOnly?: boolean;

  @ApiPropertyOptional({ default: false })
  @IsBoolean()
  @IsOptional()
  open24x7?: boolean;

  @ApiPropertyOptional({ default: false })
  @IsBoolean()
  @IsOptional()
  isOpen24x7?: boolean;

  @ApiPropertyOptional({ default: false })
  @IsBoolean()
  @IsOptional()
  vegOnly?: boolean;

  @ApiPropertyOptional({ default: false })
  @IsBoolean()
  @IsOptional()
  isVegOnly?: boolean;

  @ApiPropertyOptional({ default: false })
  @IsBoolean()
  @IsOptional()
  takeaway?: boolean;

  @ApiPropertyOptional({ default: false })
  @IsBoolean()
  @IsOptional()
  isTakeawayEnabled?: boolean;

  @ApiPropertyOptional({ default: false })
  @IsBoolean()
  @IsOptional()
  delivery?: boolean;

  @ApiPropertyOptional({ default: false })
  @IsBoolean()
  @IsOptional()
  isDeliveryEnabled?: boolean;

  @ApiPropertyOptional({ default: false })
  @IsBoolean()
  @IsOptional()
  homeDelivery?: boolean;

  @ApiPropertyOptional({ default: false })
  @IsBoolean()
  @IsOptional()
  isHomeDeliveryEnabled?: boolean;

  @ApiPropertyOptional({ default: false })
  @IsBoolean()
  @IsOptional()
  atTableDining?: boolean;

  @ApiPropertyOptional({ default: false })
  @IsBoolean()
  @IsOptional()
  isAtTableDiningEnabled?: boolean;

  @ApiPropertyOptional({ default: false })
  @IsBoolean()
  @IsOptional()
  inRoomDining?: boolean;

  @ApiPropertyOptional({ default: false })
  @IsBoolean()
  @IsOptional()
  isInRoomDiningEnabled?: boolean;

  @ApiPropertyOptional({ default: false })
  @IsBoolean()
  @IsOptional()
  inCarDining?: boolean;

  @ApiPropertyOptional({ default: false })
  @IsBoolean()
  @IsOptional()
  isInCarDiningEnabled?: boolean;

  @ApiPropertyOptional({ default: false })
  @IsBoolean()
  @IsOptional()
  posOrders?: boolean;

  @ApiPropertyOptional({ default: false })
  @IsBoolean()
  @IsOptional()
  isPosOrdersEnabled?: boolean;

  @ApiPropertyOptional({ default: false })
  @IsBoolean()
  @IsOptional()
  onlineOrders?: boolean;

  @ApiPropertyOptional({ default: false })
  @IsBoolean()
  @IsOptional()
  isOnlineOrdersEnabled?: boolean;

  @ApiPropertyOptional({ default: false })
  @IsBoolean()
  @IsOptional()
  inventory?: boolean;

  @ApiPropertyOptional({ default: false })
  @IsBoolean()
  @IsOptional()
  isInventoryEnabled?: boolean;

  @ApiPropertyOptional({ example: 'MAX CAFETERIA' })
  @IsOptional()
  @IsString()
  @MaxLength(255)
  @DisplayName()
  qrUnitName?: string;

  @ApiPropertyOptional({ example: 'MAX CAFETERIA' })
  @IsOptional()
  @IsString()
  @MaxLength(255)
  unitNameForQr?: string;

  @ApiPropertyOptional({ example: 'max@upi' })
  @IsOptional()
  @IsString()
  @MaxLength(255)
  upiId?: string;

  @ApiPropertyOptional({ example: 'HDFC Bank' })
  @IsOptional()
  @IsString()
  @MaxLength(255)
  @DisplayName()
  bankName?: string;

  @ApiPropertyOptional({ example: 'HDFC Bank - Saket' })
  @IsOptional()
  @IsString()
  @MaxLength(255)
  bankNameBranch?: string;

  @ApiPropertyOptional({ example: 'Saket' })
  @IsOptional()
  @IsString()
  @MaxLength(255)
  bankBranch?: string;

  @ApiPropertyOptional({ example: 'HDFC0001234' })
  @IsOptional()
  @IsString()
  @Matches(ifscPattern, { message: 'ifscCode must be a valid 11-character IFSC code.' })
  @MaxLength(50)
  @CodeCase()
  ifscCode?: string;

  @ApiPropertyOptional({ example: '123456789012' })
  @IsOptional()
  @IsString()
  @MaxLength(100)
  accountNumber?: string;

  @ApiPropertyOptional({ example: 'SODEXO-MID-001' })
  @IsOptional()
  @IsString()
  @MaxLength(100)
  sodexoMid?: string;

  @ApiPropertyOptional({ example: 'SODEXO-TID-001' })
  @IsOptional()
  @IsString()
  @MaxLength(100)
  sodexoTid?: string;

  @ApiPropertyOptional({ example: 'BU001' })
  @IsOptional()
  @IsString()
  @MaxLength(100)
  sunBu?: string;

  @ApiPropertyOptional({ example: 'T1' })
  @IsOptional()
  @IsString()
  @MaxLength(100)
  sunT1?: string;

  @ApiPropertyOptional({ example: 'T2' })
  @IsOptional()
  @IsString()
  @MaxLength(100)
  sunT2?: string;

  @ApiPropertyOptional({ default: true })
  @IsBoolean()
  @IsOptional()
  isActive?: boolean;

  @ApiPropertyOptional({
    description: 'The legal entity it bills under; null removes the link.',
    nullable: true,
  })
  @IsOptional()
  @IsUUID()
  legalEntityId?: string | null;
}
