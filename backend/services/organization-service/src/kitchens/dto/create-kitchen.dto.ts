import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import {
  IsBoolean,
  IsNotEmpty,
  IsOptional,
  IsString,
  IsUUID,
  Matches,
  MaxLength,
} from 'class-validator';
import { CodeCase, DisplayName } from '../../common/display-name.decorator';

const timePattern = /^([01]\d|2[0-3]):[0-5]\d$/;

export class CreateKitchenDto {
  @ApiProperty()
  @IsUUID()
  hospitalId!: string;

  @ApiPropertyOptional()
  @IsOptional()
  @IsUUID()
  locationId?: string;

  @ApiProperty({ example: 'Main Kitchen' })
  @IsNotEmpty()
  @IsString()
  @MaxLength(255)
  @DisplayName()
  kitchenName!: string;

  @ApiPropertyOptional({
    description: 'Generated by the service for new kitchens. Existing values remain supported.',
    example: 'KIT0001',
  })
  // Optional, but an update may not blank it.
  @IsNotEmpty()
  @IsOptional()
  @IsString()
  @MaxLength(50)
  @CodeCase()
  kitchenCode?: string;

  @ApiPropertyOptional({ example: '07:00' })
  @IsOptional()
  @Matches(timePattern, { message: 'openingTime must use HH:mm format.' })
  openingTime?: string;

  @ApiPropertyOptional({ example: '23:00' })
  @IsOptional()
  @Matches(timePattern, { message: 'closingTime must use HH:mm format.' })
  closingTime?: string;

  @ApiPropertyOptional({ default: true })
  @IsBoolean()
  @IsOptional()
  isActive?: boolean;
}
